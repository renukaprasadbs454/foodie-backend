-- 5. Create approval_request table for high-risk financial actions
CREATE TABLE IF NOT EXISTS approval_request (
    id             UUID PRIMARY KEY,
    action_type    VARCHAR(50) NOT NULL,
    resource_type  VARCHAR(50) NOT NULL,
    resource_id    UUID NOT NULL,
    requested_by   UUID NOT NULL REFERENCES admin_user(id) ON DELETE RESTRICT,
    approved_by    UUID REFERENCES admin_user(id) ON DELETE RESTRICT,
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDING_APPROVAL',
    payload        JSONB,
    reason         TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_approval_req_status ON approval_request(status);
CREATE INDEX IF NOT EXISTS idx_approval_req_resource ON approval_request(resource_type, resource_id);
